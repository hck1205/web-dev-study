/** 쉬운 모드에서 본문 용어 위에 띄우는 한 줄 풀이. React·브라우저에 의존하지 않는다(빌드 플러그인도 읽는다) */
export interface GlossaryTerm {
  /** 본문에 나오는 표기 그대로 (예: "캐시", "TCP", "이벤트 루프") */
  term: string;
  /** 같은 뜻의 다른 표기 (예: ["cache"]). 처음 나오는 한 곳에만 풀이가 붙는다 */
  aliases?: string[];
  /** 중학생도 알 수 있는 말로 쓴 풀이. 60자 안팎, 한 문장, 평서체. 다른 전문 용어를 쓰지 않는다 */
  plain: string;
}
