/**
 * 응용 질문: 글 두 편 이상을 엮어야 답할 수 있는 상황 문제.
 * 혼자 답을 말해 본 뒤 포인트와 비교해 자기 채점하고, 맞았으면 엮인 글들이 "응용함"(4단계)으로 올라간다.
 */
export interface AppliedQuestion {
  /** 전체에서 유일. "{영역}-{번호}" (예: "net-03") */
  id: string;
  /** 엮이는 글 slug 2~4개. posts.ts에 있는 글만 */
  posts: string[];
  /** 상황과 질문. 평서체, 2~4문장. 장애·설계·선택 상황을 구체적으로 준다 */
  prompt: string;
  /** 좋은 답이 반드시 짚어야 할 포인트 3~5개. 각 포인트는 한 문장, 결론부터 */
  points: string[];
}
